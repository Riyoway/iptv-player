const readStored = <T extends string>(key: string, allowed: readonly T[], fallback: T): T => {
  try {
    const value = localStorage.getItem(key) as T | null
    return value && allowed.includes(value) ? value : fallback
  } catch {
    return fallback
  }
}

const detectLanguage = (): Language => {
  if (typeof navigator === 'undefined') return 'en'
  const locales = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const locale of locales) {
    const normalized = locale.toLowerCase()
    if (normalized.startsWith('ja')) return 'ja'
    if (normalized.startsWith('ko')) return 'ko'
    if (normalized.startsWith('zh')) return 'zh'
    if (normalized.startsWith('en')) return 'en'
  }
  return 'en'
}

const resolveLanguage = (preference: LanguagePreference): Language => preference === 'system' ? detectLanguage() : preference

const savePreference = (key: string, value: string) => {
  try { localStorage.setItem(key, value) } catch { /* storage unavailable */ }
}

export type SettingsContextValue = {
  language: Language
  languagePreference: LanguagePreference
  themePreference: ThemePreference
  setLanguagePreference: (preference: LanguagePreference) => void
  setThemePreference: (preference: ThemePreference) => void
  t: (key: string, values?: TranslationValues) => string
}

const SettingsContext = createContext<SettingsContextValue | null>(null)

export function SettingsProvider({ children }: { children: ReactNode }) {
  const [languagePreference, setLanguagePreferenceState] = useState<LanguagePreference>(() => readStored(LANGUAGE_KEY, ['system', 'en', 'ja', 'ko', 'zh'] as const, 'system'))
  const [themePreference, setThemePreferenceState] = useState<ThemePreference>(() => readStored(THEME_KEY, ['system', 'dark', 'light'] as const, 'system'))
  const language = resolveLanguage(languagePreference)

  const setLanguagePreference = (preference: LanguagePreference) => {
    setLanguagePreferenceState(preference)
    savePreference(LANGUAGE_KEY, preference)
  }

  const setThemePreference = (preference: ThemePreference) => {
    setThemePreferenceState(preference)
    savePreference(THEME_KEY, preference)
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  useEffect(() => {
    const media = window.matchMedia('(prefers-color-scheme: dark)')
    const applyTheme = () => {
      const resolved = themePreference === 'system' ? (media.matches ? 'dark' : 'light') : themePreference
      document.documentElement.dataset.theme = resolved
    }
    applyTheme()
    media.addEventListener?.('change', applyTheme)
    return () => media.removeEventListener?.('change', applyTheme)
  }, [themePreference])

  const value = useMemo<SettingsContextValue>(() => ({
    language,
    languagePreference,
    themePreference,
    setLanguagePreference,
    setThemePreference,
    t: (key, values) => {
      const template = translations[language][key] ?? translations.en[key] ?? key
      return Object.entries(values ?? {}).reduce((text, [name, replacement]) => text.replaceAll(`{{${name}}}`, String(replacement)), template)
    },
  }), [language, languagePreference, themePreference])

  return <SettingsContext.Provider value={value}>{children}</SettingsContext.Provider>
}

export function useSettings() {
  const context = useContext(SettingsContext)
  if (!context) throw new Error('useSettings must be used inside SettingsProvider')
  return context
}
